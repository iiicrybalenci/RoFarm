const dictionaries: Record<string, Dict> = { en, es, pt, de, fr, ru, tr, zh, ja };
const [language, setLanguageSignal] = createSignal<string>("en");
export { language };

export function setLanguage(code: string) {
  const normalized = dictionaries[code] ? code : "en";
  setLanguageSignal(normalized);
  document.documentElement.lang = normalized;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dictionary = dictionaries[language()] ?? en;
  let value = dictionary[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
